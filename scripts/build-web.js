// Builds the public live demo (served by GitHub Pages from the repository root):
//   demo/kp-web.js            the extension's content code + in-page web transport (src/web)
//   demo/*.html               the demo pages from site/, with the demo script added
//   demo/metin.html           "paste your own text" page (src/web/metin.html)
//   demo/recordings/*.json    real model answers saved for the demo pages (replayed, labelled)
//   indir/kucuk-punto-eklenti.zip   the unpacked extension, ready to "Load unpacked"
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { isMain } from './env.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEMO = path.join(ROOT, 'demo');
export const DEMO_PAGES = ['netflix-tos', 'streambox-abonelik', 'streambox-abonelik-v2'];

export async function buildWeb({ quiet = false } = {}) {
  fs.mkdirSync(path.join(DEMO, 'recordings'), { recursive: true });
  await esbuild.build({
    entryPoints: [path.join(ROOT, 'src/web/entry-web.js')], outfile: path.join(DEMO, 'kp-web.js'),
    bundle: true, format: 'iife', target: 'es2020', charset: 'utf8', legalComments: 'none', logLevel: 'warning', minify: false,
    banner: { js: '// Küçük Punto canlı demo · generated by scripts/build-web.js from src/ — do not edit' }
  });
  const js = fs.readFileSync(path.join(DEMO, 'kp-web.js'), 'utf8');
  if (/\.innerHTML\s*=|insertAdjacentHTML|document\.write\(/.test(js)) throw new Error('kp-web.js contains an HTML sink');

  fs.copyFileSync(path.join(ROOT, 'site/fixture.css'), path.join(DEMO, 'fixture.css'));
  const tag = '<script src="kp-web.js" defer></script>\n';
  for (const p of DEMO_PAGES) {
    const html = fs.readFileSync(path.join(ROOT, 'site', p + '.html'), 'utf8');
    if (!html.includes('</body>')) throw new Error(p + ': no </body>');
    writeIfChanged(path.join(DEMO, p + '.html'), html.replace('</body>', tag + '</body>'));
  }
  writeIfChanged(path.join(DEMO, 'metin.html'), fs.readFileSync(path.join(ROOT, 'src/web/metin.html'), 'utf8'));

  // Netflix: the real Gemini answer from the evaluation run on the same text (eval/results/raw)
  const netflix = path.join(DEMO, 'recordings', 'netflix-tos.json');
  const raw = path.join(ROOT, 'eval/results/raw/gemini-gemini-flash-lite-latest');
  if (!fs.existsSync(netflix) && fs.existsSync(path.join(raw, 'netflix-tos.json'))) {
    const meta = JSON.parse(fs.readFileSync(path.join(raw, '_meta.json'), 'utf8'));
    const r = JSON.parse(fs.readFileSync(path.join(raw, 'netflix-tos.json'), 'utf8'));
    fs.writeFileSync(netflix, JSON.stringify({
      page: 'netflix-tos', source: 'eval/results/raw/gemini-gemini-flash-lite-latest/netflix-tos.json (değerlendirme çalıştırması, aynı metin)',
      provider: meta.provider, model: meta.model, date: meta.date, prompt_version: r.prompt_version,
      responses: r.responses.map(x => ({ text: x.text }))
    }, null, 2) + '\n');
  }

  const recs = fs.readdirSync(path.join(DEMO, 'recordings')).filter(f => f.endsWith('.json') && f !== 'index.json').map(f => f.replace(/\.json$/, '')).sort();
  writeIfChanged(path.join(DEMO, 'recordings', 'index.json'), JSON.stringify(recs) + '\n');

  fs.mkdirSync(path.join(ROOT, 'indir'), { recursive: true });
  const zipPath = path.join(ROOT, 'indir', 'kucuk-punto-eklenti.zip');
  writeIfChanged(zipPath, zipFolder(path.join(ROOT, 'extension'), 'kucuk-punto'));
  if (!quiet) console.log(`  demo/ (${DEMO_PAGES.length + 1} sayfa, kp-web.js ${(js.length / 1024).toFixed(1)} KB) · indir/kucuk-punto-eklenti.zip ${(fs.statSync(zipPath).size / 1024).toFixed(1)} KB`);
}

function writeIfChanged(file, data) {
  const buf = Buffer.isBuffer(data) ? data : Buffer.from(data);
  if (fs.existsSync(file) && fs.readFileSync(file).equals(buf)) return;
  fs.writeFileSync(file, buf);
}

// ---- minimal deterministic ZIP writer (deflate, fixed timestamps), so rebuilding changes nothing
const CRC = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c; });
const crc32 = buf => { let c = -1; for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ -1) >>> 0; };
function listFiles(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
    .flatMap(e => e.isDirectory() ? listFiles(path.join(dir, e.name), base) : [path.relative(base, path.join(dir, e.name)).split(path.sep).join('/')]);
}
export function zipFolder(dir, prefix) {
  const DOS_TIME = 0, DOS_DATE = ((2026 - 1980) << 9) | (10 << 5) | 15;
  const locals = [], centrals = [];
  let offset = 0;
  for (const rel of listFiles(dir)) {
    const data = fs.readFileSync(path.join(dir, rel));
    const comp = zlib.deflateRawSync(data, { level: 9 });
    const name = Buffer.from(`${prefix}/${rel}`, 'utf8');
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6); local.writeUInt16LE(8, 8);
    local.writeUInt16LE(DOS_TIME, 10); local.writeUInt16LE(DOS_DATE, 12); local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(name.length, 26); local.writeUInt16LE(0, 28);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(8, 10);
    central.writeUInt16LE(DOS_TIME, 12); central.writeUInt16LE(DOS_DATE, 14); central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(comp.length, 20); central.writeUInt32LE(data.length, 24); central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(offset, 42);
    locals.push(local, name, comp); centrals.push(central, name);
    offset += local.length + name.length + comp.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(centrals.length / 2, 8); end.writeUInt16LE(centrals.length / 2, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}

if (isMain(import.meta.url)) buildWeb().catch(e => { console.error(e.message); process.exit(1); });
