// Builds the unpacked extension into extension/dist and the Cypress harness bundle into site/_kp.
// Not minified on purpose: the shipped code should be as readable as the source.
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from './env.js';
import { buildWeb } from './build-web.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const common = { bundle: true, target: 'chrome116', charset: 'utf8', legalComments: 'none', logLevel: 'warning', minify: false };

export async function build({ quiet = false } = {}) {
  const banner = { js: '// Küçük Punto · generated by scripts/build.js from src/ — do not edit' };
  const jobs = [
    { entryPoints: [path.join(ROOT, 'src/content/entry-extension.js')], outfile: path.join(ROOT, 'extension/dist/content.js'), format: 'iife' },
    { entryPoints: [path.join(ROOT, 'src/background/sw.js')], outfile: path.join(ROOT, 'extension/dist/background.js'), format: 'esm' },
    { entryPoints: [path.join(ROOT, 'src/options/options.js')], outfile: path.join(ROOT, 'extension/dist/options.js'), format: 'iife' },
    { entryPoints: [path.join(ROOT, 'src/content/entry-harness.js')], outfile: path.join(ROOT, 'site/_kp/harness.js'), format: 'iife' }
  ];
  const t0 = Date.now();
  await Promise.all(jobs.map(j => esbuild.build({ ...common, ...j, banner })));
  // the content script must never ship code paths that write HTML strings
  const content = fs.readFileSync(path.join(ROOT, 'extension/dist/content.js'), 'utf8');
  if (/\.innerHTML\s*=|insertAdjacentHTML|document\.write\(/.test(content)) throw new Error('content.js contains an HTML sink');
  // the public live demo (GitHub Pages) uses the same sources; keep it in step with every build
  await buildWeb({ quiet: true });
  if (!quiet) {
    for (const j of jobs) console.log(`  ${path.relative(ROOT, j.outfile).padEnd(28)} ${(fs.statSync(j.outfile).size / 1024).toFixed(1)} KB`);
    console.log(`build ok (${Date.now() - t0} ms)`);
  }
}

if (isMain(import.meta.url)) build().catch(e => { console.error(e.message); process.exit(1); });
